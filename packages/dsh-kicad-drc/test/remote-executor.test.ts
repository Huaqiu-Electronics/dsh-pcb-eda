test('调用方取消时中断请求并抛 DrcAbortedError，不进失败冷却', async () => {
  const { pcb, cleanup } = makeFixture()
  try {
    // lint 挂住直到被 abort：模拟远端跑到一半用户取消
    const fetchImpl = async (input: RequestInfo | URL, init?: RequestInit): Promise<Response> => {
      const url = String(input)
      if (url.endsWith('/api/s/health')) return jsonResponse({ status: 'ok', version: '0.1.0' })
      if (url.endsWith('/api/s/upload')) return jsonResponse({ sessionToken: 'session-1' })
      return new Promise<Response>((_resolve, reject) => {
        init?.signal?.addEventListener('abort', () => {
          reject(new DOMException('This operation was aborted', 'AbortError'))
        })
      })
    }
    const exec = new RemoteExecutor({ baseUrl: 'http://unit-test', fetchImpl: fetchImpl as typeof fetch })
    const ctrl = new AbortController()
    const running = exec.run({ pcbPath: pcb, signal: ctrl.signal })
    setTimeout(() => ctrl.abort(), 10)
    await assert.rejects(running, (e: unknown) => e instanceof DrcAbortedError)

    // 取消不是失败：remote 不该因此被冷却一分钟
    const health = await exec.probe()
    assert.equal(health.available, true)
  } finally {
    cleanup()
  }
})
