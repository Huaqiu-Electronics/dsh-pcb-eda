test('失败进冷却后，跑通一次即清冷却（否则会一直误报 remote 不可用）', async () => {
  const { pcb, cleanup } = makeFixture()
  try {
    let failLint = true
    const { fetchImpl } = mockFetch({
      lint: () => (failLint
        ? jsonResponse({ error: 'boom' }, 500)
        : jsonResponse(LINT_BODY)),
    })
    const executor = new RemoteExecutor({ baseUrl: 'http://unit-test', fetchImpl })

    await assert.rejects(() => executor.run({ pcbPath: pcb }))
    assert.equal((await executor.probe()).available, false) // 冷却期内：不再打服务
    assert.match(String((await executor.probe()).reason), /冷却期/)

    failLint = false
    const result = await executor.run({ pcbPath: pcb })
    assert.equal(result.exitCode, 0)
    // 服务明明恢复了，探测不能再报不可用——否则自适应选择会被过期状态带去走 local
    const health = await executor.probe()
    assert.equal(health.available, true)
  } finally {
    cleanup()
  }
})

