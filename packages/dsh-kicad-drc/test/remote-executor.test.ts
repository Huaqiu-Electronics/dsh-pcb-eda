/** 记录每次请求的 URL / 头 / 方法，并按路径返回预设响应。 */
function mockFetch(handlers: {
  upload?: () => Response
  lint?: () => Response
  health?: () => Response
  druGet?: () => Response
  druPut?: (content: string) => Response
  drcRulesGet?: () => Response
  drcRulesPut?: () => Response
  drcStatus?: () => Response
}): { fetchImpl: typeof fetch, calls: Call[] } {
  const calls: Call[] = []
  const fetchImpl = async (input: RequestInfo | URL, init?: RequestInit): Promise<Response> => {
    const url = String(input)
    calls.push({
      url,
      method: init?.method ?? 'GET',
      headers: (init?.headers as Record<string, string>) ?? {},
    })
    if (url.endsWith('/api/s/health')) {
      return (handlers.health ?? (() => jsonResponse({ status: 'ok', version: '0.1.0' })))()
    }
    if (url.endsWith('/api/s/upload')) {
      return (handlers.upload ?? (() => jsonResponse({
        sessionToken: 'session-1', fileName: 'board.kicad_pcb', reused: false,
      })))()
    }
    if (url.endsWith('/api/s/dru')) {
      if ((init?.method ?? 'GET') === 'GET') {
        return (handlers.druGet ?? (() => jsonResponse({
          fileName: 'board.kicad_dru', content: DRU_GENERATED, source: 'GENERATED',
        })))()
      }
      const content = String((JSON.parse(String(init?.body)) as { content?: string }).content ?? '')
      return (handlers.druPut ?? ((c: string) => jsonResponse({
        fileName: 'board.kicad_dru', content: c, source: 'USER_EDITED',
      })))(content)
    }
    if (url.endsWith('/api/s/drc-rules')) {
      if ((init?.method ?? 'GET') === 'GET') {
        return (handlers.drcRulesGet ?? (() => jsonResponse(DRC_RULES_BODY)))()
      }
      return (handlers.drcRulesPut ?? (() => jsonResponse(DRC_RULES_BODY)))()
    }
    if (url.endsWith('/api/s/drc-status')) {
      return (handlers.drcStatus ?? (() => jsonResponse({
        available: true, cliRunnerUrl: 'local://test (kicad-cli)',
      })))()
    }
    if (url.endsWith('/api/s/lint-drc')) {
      return (handlers.lint ?? (() => jsonResponse(LINT_BODY)))()
    }
    throw new Error(`unexpected url: ${url}`)
  }
  return { fetchImpl: fetchImpl as unknown as typeof fetch, calls }
}

test('RemoteExecutor 走 pcblint 两步握手，并把报告落盘到 PCB 同目录', async () => {
  const { dir, pcb, cleanup } = makeFixture()
  try {
    const { fetchImpl, calls } = mockFetch({})
    const executor = new RemoteExecutor({ baseUrl: 'http://unit-test', fetchImpl })
    const result = await executor.run({ pcbPath: pcb })

    assert.deepEqual(calls.map((c) => c.url), [
      'http://unit-test/api/s/upload',
      'http://unit-test/api/s/drc-rules',
      'http://unit-test/api/s/lint-drc',
    ])
    // lint 必须带会话令牌：服务端靠它找回刚上传的板
    assert.equal(calls[2]?.headers['X-Session-Token'], 'session-1')

    assert.equal(result.exitCode, 0)
    assert.equal(result.reportFormat, 'pcblint')
    assert.equal(result.kicadCliPath, 'remote:http://unit-test')
    // 文件名带格式后缀：同一块板换后端跑，不能把 local 的报告覆盖掉
    assert.equal(result.drcJsonPath, join(dir, 'board_drc.pcblint.json'))
    assert.ok(existsSync(result.drcJsonPath as string))

    const saved = JSON.parse(readFileSync(result.drcJsonPath as string, 'utf-8'))
    assert.equal(saved.format, 'pcblint')
    assert.equal(saved.source, 'board.kicad_pcb')
    assert.equal(saved.endpoint, 'http://unit-test')
    // 服务端字段原样保留（不裁剪、不改写）
    assert.equal(saved.violations.length, 2)
    assert.equal(saved.violations[0].confidence, 'HIGH')
    assert.equal(saved.kicadDrcUsed, true)
    assert.deepEqual(saved.groups, LINT_BODY.groups)
    // 抑制条数要透出成提示，避免被当成"零违规"
    assert.match(result.stderr, /过滤掉 2 条/)
  } finally {
    cleanup()
  }
})

