import { test } from 'node:test'
import assert from 'node:assert/strict'
import {
  PROJECT_DRU_MARKER,
  PROJECT_RULES_MARKER,
  buildProjectRuleSet,
  describeProjectRules,
  injectProjectDru,
  injectProjectRules,
  stripInjectedRules,
} from '../src/project-rules.ts'

/** 取自真实工程（EchoEar 板-1）的板级约束片段。 */
const PRO = {
  board: {
    design_settings: {
      rules: {
        min_clearance: 0.102,
        min_track_width: 0.102,
        min_via_diameter: 0.406,
        min_via_annular_width: 0.0505,
        min_through_hole_diameter: 0.3,
        min_hole_clearance: 0.152,
        min_hole_to_hole: 0.152,
        min_copper_edge_clearance: 0.254,
        min_silk_clearance: 0.152,
        min_text_height: 0.8,
        min_microvia_diameter: 0.2,
      },
    },
  },
}

test('把板级约束翻成 dru 规则，并声明来源', () => {
  const set = buildProjectRuleSet(JSON.stringify(PRO), 'board.kicad_pro')
  assert.equal(set.source, 'board.kicad_pro')
  assert.equal(set.applied.length, 8)
  const byConstraint = Object.fromEntries(set.applied.map((r) => [r.constraint, r.mm]))
  assert.equal(byConstraint.track_width, 0.102)
  assert.equal(byConstraint.annular_width, 0.0505)
  assert.equal(byConstraint.edge_clearance, 0.254)

  assert.ok(set.block.startsWith(PROJECT_RULES_MARKER))
  assert.match(set.block, /\(constraint track_width \(min 0\.102mm\)\)/)
  // 小数点不能被写成科学计数法
  assert.match(set.block, /\(constraint annular_width \(min 0\.0505mm\)\)/)
})

test('silk/text/microvia 约束不注入，并给出原因', () => {
  const set = buildProjectRuleSet(JSON.stringify(PRO), 'board.kicad_pro')
  const skipped = new Set(set.skipped.map((s) => s.key))
  assert.ok(skipped.has('min_silk_clearance'))
  assert.ok(skipped.has('min_text_height'))
  assert.ok(skipped.has('min_microvia_diameter'))
  for (const s of set.skipped) assert.ok(s.reason.length > 0)
  // 不注入的约束不能出现在规则块里
  assert.doesNotMatch(set.block, /silk_clearance/)
  assert.doesNotMatch(set.block, /text_height/)
})

test('值为 0 表示工程未启用该约束，必须跳过而不是注入 (min 0)', () => {
  const set = buildProjectRuleSet(
    JSON.stringify({ board: { design_settings: { rules: { min_clearance: 0, min_track_width: 0.15 } } } }),
    'x.kicad_pro',
  )
  assert.deepEqual(set.applied.map((r) => r.constraint), ['track_width'])
  const clearance = set.skipped.find((s) => s.key === 'min_clearance')
  assert.ok(clearance)
  assert.match(clearance.reason, /未启用/)
})

test('没有 rules 字段时产出空块，调用方据此跳过注入', () => {
  const set = buildProjectRuleSet(JSON.stringify({ board: {} }), 'empty.kicad_pro')
  assert.equal(set.applied.length, 0)
  assert.equal(set.block, '')
})

test('非法 JSON 抛错，由调用方降级为不注入', () => {
  assert.throws(() => buildProjectRuleSet('not json', 'bad.kicad_pro'), /不是合法 JSON/)
})

test('重复注入不叠加：同一份规则注入两次只保留一段', () => {
  const set = buildProjectRuleSet(JSON.stringify(PRO), 'board.kicad_pro')
  const base = '(version 1)\n# Auto-generated by PCBLint\n(rule "pcblint_ic_keepout" (constraint disallow track))\n'
  const once = injectProjectRules(base, set)
  const twice = injectProjectRules(once, set)
  assert.equal(twice, once, '第二次结果应与第一次完全一致')
  assert.equal(once.split(PROJECT_RULES_MARKER).length - 1, 1, 'marker 只出现一次')
  assert.equal((twice.match(/\(rule "dsh_project_/g) ?? []).length, 8)
  // 服务端自动生成的规则必须保留
  assert.match(twice, /pcblint_ic_keepout/)
})

test('stripInjectedRules 只切掉注入段，不动服务端内容', () => {
  const base = '(version 1)\n(rule "pcblint_keepout" (constraint disallow track))'
  const set = buildProjectRuleSet(JSON.stringify(PRO), 'board.kicad_pro')
  assert.equal(stripInjectedRules(injectProjectRules(base, set)).trim(), base)
  assert.equal(stripInjectedRules(base), base)
})

test('摘要文本说明来源与条数，便于写进 stderr', () => {
  const set = buildProjectRuleSet(JSON.stringify(PRO), 'board.kicad_pro')
  const text = describeProjectRules(set)
  assert.match(text, /board\.kicad_pro/)
  assert.match(text, /8 条板级约束/)
  assert.match(text, /track_width 0\.102/)
})

/** 带网络类的工程：Default 之外还有一个 Power 类。 */
const PRO_WITH_CLASSES = {
  board: { design_settings: { rules: { min_clearance: 0.102, min_track_width: 0.102 } } },
  net_settings: {
    classes: [
      { name: 'Default', clearance: 0.101, track_width: 0.254, via_diameter: 0.61 },
      { name: 'Power', clearance: 0.4, track_width: 0.5, via_diameter: 0.8 },
      { name: 'RF', clearance: 0, track_width: 0.3 },
    ],
  },
}

test('网络类只注入 clearance，且带 NetClass 条件', () => {
  const set = buildProjectRuleSet(JSON.stringify(PRO_WITH_CLASSES), 'board.kicad_pro')
  const classes = set.applied.filter((r) => r.netclass !== undefined)
  assert.deepEqual(classes, [{ constraint: 'clearance', mm: 0.4, netclass: 'Power' }])
  assert.match(
    set.block,
    /\(rule "dsh_netclass_Power_clearance"\n  \(condition "A\.NetClass == 'Power'"\)\n  \(constraint clearance \(min 0\.4mm\)\)\)/,
  )
  // 实测：原生 netclass 的线宽/过孔盘不做 DRC 检查，注入会凭空放大，故不注入
  assert.doesNotMatch(set.block, /dsh_netclass_Power_track_width/)
  assert.doesNotMatch(set.block, /dsh_netclass_Power_via_diameter/)
})

test('Default 类与 clearance 为 0 的类不生成条件规则', () => {
  const set = buildProjectRuleSet(JSON.stringify(PRO_WITH_CLASSES), 'board.kicad_pro')
  assert.doesNotMatch(set.block, /NetClass == 'Default'/)
  // 已应用的 8 类板级约束里本来就有 clearance，但那是无条件的
  const unconditional = set.applied.filter((r) => r.netclass === undefined).map((r) => r.constraint)
  assert.ok(unconditional.includes('clearance'))
  assert.ok(set.skipped.some((s) => s.key === 'netclass:RF:clearance'))
})

test('类名里的引号与特殊字符不会破坏规则语法', () => {
  const pro = {
    net_settings: { classes: [{ name: "O'Brien 5V", clearance: 0.3 }] },
  }
  const set = buildProjectRuleSet(JSON.stringify(pro), 'board.kicad_pro')
  assert.match(set.block, /dsh_netclass_O_Brien_5V_clearance/)
  assert.match(set.block, /A\.NetClass == 'O\\'Brien 5V'/)
})

test('工程 .kicad_dru 追加在生成块之后，去掉重复的版本声明', () => {
  const base = '(version 1)\n(rule "pcblint_keepout" (constraint disallow track))'
  const dru = "(version 1)\n(rule \"my_rule\" (constraint clearance (min 0.5mm)))"
  const merged = injectProjectDru(base, dru)
  assert.match(merged, /pcblint_keepout/, '服务端规则必须保留')
  assert.match(merged, /rules from project \.kicad_dru/)
  assert.equal((merged.match(/\(version 1\)/g) ?? []).length, 1, '不能出现第二个版本声明')
  // KiCad 后出现的规则覆盖先出现的：工程自定义规则必须排在生成块之后
  const ordered = injectProjectDru(
    injectProjectRules(base, buildProjectRuleSet(JSON.stringify(PRO), 'board.kicad_pro')),
    dru,
  )
  assert.ok(
    ordered.indexOf('my_rule') > ordered.indexOf(PROJECT_RULES_MARKER),
    '工程规则应在生成块之后',
  )
})

test('重复注入工程 .kicad_dru 保持幂等', () => {
  const base = '(version 1)\n(rule "pcblint_keepout" (constraint disallow track))'
  const dru = "(version 1)\n(rule \"my_rule\" (constraint clearance (min 0.5mm)))"
  const once = injectProjectDru(base, dru)
  const twice = injectProjectDru(once, dru)
  assert.equal(twice, once)
  assert.equal(twice.split(PROJECT_DRU_MARKER).length - 1, 1)
})

test('没有工程 .kicad_dru 时不改变会话规则', () => {
  const base = '(version 1)\n(rule "pcblint_keepout" (constraint disallow track))'
  assert.equal(injectProjectDru(base, undefined).trim(), base)
  assert.equal(injectProjectDru(base, '   ').trim(), base)
})
