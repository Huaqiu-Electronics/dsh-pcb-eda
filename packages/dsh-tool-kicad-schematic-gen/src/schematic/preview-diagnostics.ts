/** File-format diagnostics for preview preflight and KiCad export failures. */
import { children, parse, quote, type Form } from './sexpr.ts'

/** A located format problem; positions use one-based lines and columns. */
export interface PreviewDiagnostic {
  field: string
  line?: number
  column?: number
  actual?: string
  expected?: string
  message: string
  suggestion: string
}

/** Model-visible preview failure; an unknown CLI cause has no invented field diagnosis. */
export interface PreviewErrorDetails {
  status: 'error'
  code: string
  stage: 'format_preflight' | 'kicad_load' | 'svg_export'
  schematicPath: string
  message: string
  diagnostics: PreviewDiagnostic[]
  retryUnchanged: boolean
  nextAction: string
  exitCode?: number
  stdout?: string
  stderr?: string
}

/** Preserve JSON diagnostics in the DSH failed-tool result instead of a successful output.
 * @param details Located problems or the original CLI failure and recovery guidance.
 */
export class PreviewError extends Error {
  constructor(readonly details: PreviewErrorDetails) {
    super(JSON.stringify(details))
    this.name = 'PreviewError'
  }
}

/** Parse one preview source and reject known file-format errors without editing it.
 * @param text Exact source contents, including quoted and unquoted atoms.
 * @param schematicPath File reported in a failed tool result, including child files.
 * @returns Parsed root for source mapping; throws PreviewError for detected problems.
 */
export function validatePreviewSchematic(text: string, schematicPath: string): Form {
  let root: Form
  try { root = parse(text) }
  catch (error) {
    throw new PreviewError({ status: 'error', code: 'SCHEMATIC_INVALID_SYNTAX', stage: 'format_preflight',
      schematicPath, message: 'The schematic S-expression could not be parsed.', diagnostics: [{
        field: 'document', message: error instanceof Error ? error.message : String(error),
        suggestion: 'Correct the schematic parentheses and string syntax in the project copy.',
      }], retryUnchanged: false,
      nextAction: 'Repair the reported schematic syntax before retrying preview. Do not change image dimensions or outputDir.' })
  }
  if (root.head !== 'kicad_sch') {
    throw new PreviewError({ status: 'error', code: 'SCHEMATIC_INVALID_ROOT', stage: 'format_preflight',
      schematicPath, message: 'The file must contain a kicad_sch root form.', diagnostics: [{
        field: 'document', line: 1, column: 1, actual: root.head, expected: 'kicad_sch',
        message: 'This file is not a KiCad schematic.', suggestion: 'Pass the project .kicad_sch file rather than a symbol library or other file.',
      }], retryUnchanged: false, nextAction: 'Select a KiCad schematic before retrying preview.' })
  }
  const diagnostics: PreviewDiagnostic[] = []
  for (const instances of children(root, 'sheet_instances')) {
    for (const path of children(instances, 'path')) {
      for (const page of children(path, 'page')) {
        const atom = page.items[1]
        if (page.items.length === 2 && typeof atom === 'string' && /^"(?:[^"\\]|\\.)*"$/u.test(atom)) continue
        const prefix = text.slice(0, page.start)
        diagnostics.push({ field: 'sheet_instances.path.page',
          line: prefix.split('\n').length, column: page.start - prefix.lastIndexOf('\n'),
          actual: text.slice(page.start, page.end).slice(0, 200),
          expected: `(page ${quote(typeof atom === 'string' && !atom.startsWith('"') ? atom : '<existing-page-number>')})`,
          message: 'The sheet page number must be one quoted string, not a numeric atom.',
          suggestion: 'Quote the existing page number in the project copy; for example, change (page 1) to (page "1"). Keep the original page number.',
        })
      }
    }
  }
  if (diagnostics.length > 0) {
    throw new PreviewError({ status: 'error', code: 'SCHEMATIC_INVALID_FIELD', stage: 'format_preflight',
      schematicPath, message: 'Known schematic field-format errors were found before SVG export.', diagnostics,
      retryUnchanged: false, nextAction: 'Correct diagnostics in the project copy and its generator, then retry preview. No SVG or PNG was generated by this call. Do not change image dimensions or outputDir.' })
  }
  return root
}

/** Convert a nonzero KiCad SVG exit into a failed-tool diagnostic without guessing a field.
 * @param schematicPath Root passed to KiCad; the CLI may report an invalid child in its output.
 * @param result Original process output and exit code.
 * @returns Error containing failure stage, original output, and recovery instructions.
 */
export function previewExportError(schematicPath: string,
  result: { exitCode: number; stdout: string; stderr: string }): PreviewError {
  const longOutput = [...result.stderr.matchAll(/['"]([^'"]+\.svg)['"]/gu)]
    .map(match => match[1]!).find(path => path.length >= 260)
  if (process.platform === 'win32' && longOutput && /创建文件|(?:create|write).*file/iu.test(result.stderr)) {
    return new PreviewError({ status: 'error', code: 'PREVIEW_OUTPUT_PATH_TOO_LONG', stage: 'svg_export', schematicPath,
      message: 'KiCad reported a file creation failure at a Windows MAX_PATH-length SVG path.',
      diagnostics: [{ field: 'outputDir', actual: longOutput, message: `SVG output path has ${longOutput.length} characters.`,
        suggestion: 'Use a shorter project-local outputDir.' }], exitCode: result.exitCode, stdout: result.stdout, stderr: result.stderr,
      retryUnchanged: false, nextAction: 'Retry with a shorter outputDir inside the workspace. Preserve the schematic and do not treat this output-file failure as invalid schematic syntax.' })
  }
  const loadFailed = /加载原理图失败|(?:failed|unable|cannot|could not) to (?:load|open) (?:the )?schematic|error loading schematic/iu
    .test(`${result.stderr}\n${result.stdout}`)
  return new PreviewError({ status: 'error', code: loadFailed ? 'SCHEMATIC_LOAD_FAILED' : 'KICAD_SVG_EXPORT_FAILED',
    stage: loadFailed ? 'kicad_load' : 'svg_export', schematicPath,
    message: loadFailed ? 'KiCad could not load the schematic. The exact invalid field was not identified.'
      : 'KiCad SVG export failed. The exact cause was not identified.',
    diagnostics: [], exitCode: result.exitCode, stdout: result.stdout, stderr: result.stderr,
    retryUnchanged: false,
    nextAction: loadFailed
      ? 'Inspect the reported schematic and referenced child files using the original CLI output or KiCad load diagnostics. Repair the project copy before retrying. Do not assume a page-number error, read a PNG, change image dimensions or outputDir, or export a netlist to repair loading.'
      : 'Use the original CLI output to diagnose the export failure before retrying. No preview PNG is available from this call; do not infer a file-format cause or construct image paths.',
  })
}
